# Regenerate frontend/src/lib/api/schema.d.ts from the backend's OpenAPI schema.
# Usage: powershell -ExecutionPolicy Bypass -File scripts\gen-api-types.ps1 [-Check]
#   -Check  fail if the committed types are out of date (used by scripts\check.ps1)
param([switch]$Check)
. "$PSScriptRoot\common.ps1"
Assert-BackendEnv
Assert-FrontendDeps

$schemaJson = Join-Path ([IO.Path]::GetTempPath()) "traid-openapi-$PID.json"
$generated = Join-Path ([IO.Path]::GetTempPath()) "traid-schema-$PID.d.ts"
$target = Join-Path $FrontendDir 'src\lib\api\schema.d.ts'

try {
    Push-Location $BackendDir
    & $BackendPython -m app.openapi_export $schemaJson
    if ($LASTEXITCODE -ne 0) { throw 'OpenAPI export failed' }
    Pop-Location

    Push-Location $FrontendDir
    npx --no-install openapi-typescript $schemaJson --output $generated --alphabetize | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'openapi-typescript failed' }
    Pop-Location

    $header = "// Generated by scripts/gen-api-types.ps1 from the backend OpenAPI schema. Do not edit.`n"
    $content = $header + (Get-Content -Raw -Encoding UTF8 $generated)

    if ($Check) {
        $current = if (Test-Path $target) { Get-Content -Raw -Encoding UTF8 $target } else { '' }
        if ($current.Replace("`r`n", "`n") -ne $content.Replace("`r`n", "`n")) {
            throw 'API types are out of date. Run scripts\gen-api-types.ps1 and commit the result.'
        }
        Write-Host 'API types are up to date'
    } else {
        [IO.File]::WriteAllText($target, $content.Replace("`r`n", "`n"), (New-Object System.Text.UTF8Encoding $false))
        Write-Host "Wrote $target"
    }
} finally {
    Remove-Item -ErrorAction SilentlyContinue $schemaJson, $generated
}
